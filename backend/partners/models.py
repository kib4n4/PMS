# backend/partners/models.py

import uuid

from django.conf import settings
from django.core.exceptions import ValidationError
from django.db import models
from django.utils import timezone


class PayoutAccount(models.Model):
    """M-Pesa number a Reseller or Investor is paid out to via B2C from
    the platform's own account. Landlords do NOT use this model under
    Option B — they keep their own paybill's funds directly."""

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    phone_number = models.CharField(max_length=20)
    label = models.CharField(max_length=100, blank=True)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.label or 'Payout account'} — {self.phone_number}"


class Reseller(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="reseller_profile"
    )
    full_name = models.CharField(max_length=255)
    payout_account = models.ForeignKey(
        PayoutAccount, on_delete=models.PROTECT, related_name="resellers"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.full_name


class CommissionBasis(models.TextChoices):
    PERCENT_OF_PLATFORM_FEE = "percent_of_platform_fee", "% of platform fee revenue from referred landlord"


class ReferralCommissionRule(models.Model):
    """
    Rate a Reseller earns on the PLATFORM's own fee revenue generated by
    a landlord they referred. Duration can be perpetual or time-boxed
    (e.g. 12 months from the landlord's onboarding date) — configurable
    without a code deploy.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    reseller = models.ForeignKey(Reseller, on_delete=models.CASCADE, related_name="commission_rules")
    landlord = models.ForeignKey(
        "landlords.Landlord", on_delete=models.CASCADE, related_name="referral_commission_rules"
    )
    basis = models.CharField(
        max_length=40, choices=CommissionBasis.choices, default=CommissionBasis.PERCENT_OF_PLATFORM_FEE
    )
    rate_percent = models.DecimalField(max_digits=5, decimal_places=2, help_text="e.g. 10.00 for 10%")
    is_perpetual = models.BooleanField(default=True)
    expires_at = models.DateTimeField(
        null=True, blank=True, help_text="Only used if is_perpetual is False"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.reseller.full_name} earns {self.rate_percent}% on {self.landlord.full_name}"

    def _is_currently_active(self) -> bool:
        return self.is_perpetual or bool(self.expires_at and self.expires_at > timezone.now())

    def clean(self):
        super().clean()
        if not self._is_currently_active():
            return
        conflicting = ReferralCommissionRule.objects.filter(reseller=self.reseller, landlord_id=self.landlord_id)
        if self.pk:
            conflicting = conflicting.exclude(pk=self.pk)
        for other in conflicting:
            if other._is_currently_active():
                raise ValidationError(
                    "This reseller already has an active commission rule for this landlord "
                    f"(rule {other.pk}). billing/tasks.py picks one arbitrarily via .first() "
                    "when duplicates exist — expire or delete the old rule first."
                )


class Investor(models.Model):
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.OneToOneField(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="investor_profile"
    )
    full_name = models.CharField(max_length=255)
    payout_account = models.ForeignKey(
        PayoutAccount, on_delete=models.PROTECT, related_name="investors"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.full_name


class RevenueShareBasis(models.TextChoices):
    GROSS_FEE_REVENUE = "gross_fee_revenue", "% of gross platform fee revenue"
    NET_PROFIT = "net_profit", "% of net profit"


class RevenueShareAgreement(models.Model):
    """
    An Investor's revenue/equity share of platform fee revenue —
    portfolio-wide or scoped to a specific Organization. Independent of
    referral attribution (that's the Reseller's mechanism).
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    investor = models.ForeignKey(Investor, on_delete=models.CASCADE, related_name="agreements")
    organization = models.ForeignKey(
        "landlords.Organization", on_delete=models.CASCADE, null=True, blank=True,
        related_name="investor_agreements",
        help_text="Leave blank for a portfolio-wide (all-organizations) agreement",
    )
    basis = models.CharField(max_length=30, choices=RevenueShareBasis.choices)
    rate_percent = models.DecimalField(max_digits=5, decimal_places=2)
    payout_cadence = models.CharField(
        max_length=20, choices=[("monthly", "Monthly"), ("quarterly", "Quarterly")], default="monthly"
    )
    effective_start = models.DateField()
    effective_end = models.DateField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        scope = self.organization.name if self.organization else "Portfolio-wide"
        return f"{self.investor.full_name} — {self.rate_percent}% ({scope})"


class DisbursementRecipientType(models.TextChoices):
    RESELLER = "reseller", "Reseller"
    INVESTOR = "investor", "Investor"


class DisbursementStatus(models.TextChoices):
    PENDING = "pending", "Pending"
    SENT = "sent", "Sent"
    CONFIRMED = "confirmed", "Confirmed"
    FAILED = "failed", "Failed"


class Disbursement(models.Model):
    """
    A B2C payout batch to a Reseller or Investor, funded from the
    platform's OWN collected fee revenue. Landlords are never a
    Disbursement target under Option B.
    """

    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    recipient_type = models.CharField(max_length=10, choices=DisbursementRecipientType.choices)
    reseller = models.ForeignKey(
        Reseller, on_delete=models.PROTECT, null=True, blank=True, related_name="disbursements"
    )
    investor = models.ForeignKey(
        Investor, on_delete=models.PROTECT, null=True, blank=True, related_name="disbursements"
    )
    amount = models.DecimalField(max_digits=12, decimal_places=2)
    fee_ledger_entries = models.ManyToManyField(
        "billing.FeeLedgerEntry", related_name="disbursements", blank=True,
        help_text="Which FeeLedgerEntry records this clears (for Reseller payouts)",
    )
    status = models.CharField(max_length=20, choices=DisbursementStatus.choices, default=DisbursementStatus.PENDING)
    mpesa_conversation_id = models.CharField(
        max_length=100, blank=True, unique=True, null=True,
        help_text="Safaricom ConversationID — dedupe key for idempotent B2C result handling",
    )
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        who = self.reseller or self.investor
        return f"Disbursement {self.amount} to {who} ({self.status})"

    def clean(self):
        super().clean()
        if self.recipient_type == DisbursementRecipientType.RESELLER:
            if not self.reseller_id or self.investor_id:
                raise ValidationError("recipient_type=reseller requires reseller set and investor blank.")
        elif self.recipient_type == DisbursementRecipientType.INVESTOR:
            if not self.investor_id or self.reseller_id:
                raise ValidationError("recipient_type=investor requires investor set and reseller blank.")